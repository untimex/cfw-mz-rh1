static int is_35elk(void)
{
    return (*(volatile const uint8_t *)0x8004dd & 1) &&
           *(volatile const uint16_t *)0x800506 == 0x4d52 &&
           *(volatile const uint32_t *)0x800508 == 0x42323043;
}

void cfw_title_wide_format(unsigned caps, uint8_t *text, uint16_t *length,
                           uint8_t *state, uint8_t *encoding, unsigned device)
{
    unsigned source_length = *length;
    int widen = device == 2 && *encoding == 0x84 && source_length &&
                source_length <= 0x44 && is_35elk();
    cfw_format_remote_name(caps, text, length, state, encoding, device);
    if (!widen || *encoding != 0x90 || !*length)
        return;

    /* Use the native double-byte format chosen for working 35ELK titles.
       The original UTF-16 byte count also bounds the double-byte output. */
    uint8_t converted[0x44];
    unsigned written = 0;
    for (unsigned i = 0; i < *length && written + 1 < source_length; ++i) {
        unsigned byte = text[i];
        unsigned pair = 0x81a0;
        if (byte >= 0x20 && byte <= 0x7e) {
            pair = wide_ascii[byte - 0x20];
        } else if (byte >= 0xa1 && byte <= 0xdf) {
            pair = wide_kana[byte - 0xa1];
        } else if (i + 1 < *length &&
                   ((byte >= 0x81 && byte <= 0x9f) || (byte >= 0xe0 && byte <= 0xef))) {
            pair = byte << 8 | text[++i];
        }
        converted[written++] = pair >> 8;
        converted[written++] = pair;
    }
    for (unsigned i = 0; i < written; ++i)
        text[i] = converted[i];
    text[written] = 0;
    *length = written;
    *encoding = 2;
}

__attribute__((naked)) void cfw_title_wide_format_hook(void)
{
    __asm__ volatile (
        ".syntax unified\n"
        "push {r4, lr}\n"
        "ldr r4, [sp, #0x30]\n"
        "push {r4}\n"
        "ldr r4, [sp, #12]\n"
        "push {r4}\n"
        "bl cfw_title_wide_format\n"
        "add sp, #8\n"
        "pop {r4, pc}\n"
    );
}
