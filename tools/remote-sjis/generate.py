"""Generate the shared CP932 table using Python's codec and the OLED reading data."""
import re
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src/extension-code/src"
TRAILS = list(range(0x40, 0x7f)) + list(range(0x80, 0xfd))
LEADS = list(range(0x81, 0xa0)) + list(range(0xe0, 0xeb)) + [0xed, 0xee, 0xfa, 0xfb, 0xfc]


def array(name, width, values, placement=""):
    lines = [", ".join(hex(x) for x in values[i:i+16]) for i in range(0, len(values), 16)]
    return f"static const uint{width}_t {name}[] {placement}= {{\n    " + ",\n    ".join(lines) + "\n};\n"


def codepoint(lead, trail):
    try:
        return ord(bytes((lead, trail)).decode("cp932"))
    except UnicodeDecodeError:
        return 0


def encode_row(row):
    result = []
    previous = 0
    i = 0
    while i < len(row):
        cp = row[i]
        delta = cp - previous
        if not cp:
            end = i + 1
            while end < len(row) and not row[end]:
                end += 1
            result.extend((0x7e, end - i))
            previous = 0
            i = end
            continue
        if (i + 1 < len(row) and 1 <= delta <= 8
                and 1 <= row[i + 1] - cp <= 8):
            result.append(0x80 | ((delta - 1) << 3) | (row[i + 1] - cp - 1))
            previous = row[i + 1]
            i += 2
            continue
        if -16 <= delta <= 47:
            result.append(0xd0 + delta)
        elif 0x4e00 <= cp < 0xa000:
            literal = cp - 0x4dff
            result.extend((literal >> 8, literal & 255))
        else:
            result.extend((0x7f, cp >> 8, cp & 255))
        previous = cp
        i += 1
    return result


rows = [[codepoint(lead, trail) for trail in TRAILS] for lead in LEADS]
prefix, suffix, offsets, ranges = [], [], [], []
for row in rows[:-3]:
    encoded = encode_row(row)
    # Keep the two byte arrays entirely inside the reserved CFW flash space.
    if not suffix and len(prefix) + len(encoded) <= 0xf60:
        offsets.append(0x8000 + len(prefix))
        prefix.extend(encoded)
    else:
        offsets.append(len(suffix))
        suffix.extend(encoded)
    low = min((cp for cp in row if cp), default=0)
    high = max(row)
    ranges.extend((low >> 8, high >> 8))

# Compare every legacy OLED reading to the existing Unicode reading table.
# Compatibility ideographs and characters absent from the Unicode table use exceptions.
pinyin_path = SRC / "han_readings.inc"
old = pinyin_path.read_text()


def data(name):
    body = re.search(r"\b" + name + r"\[\] = \{(.*?)\};", old, re.S)
    return [int(num, 16) for num in re.findall(r"0x[0-9a-f]+", body[1])]


def packed(table, index):
    offset = index + (index >> 3)
    return ((table[offset] | table[offset + 1] << 8) >> (index & 7)) & 511


mask, pages, han = (data(x) for x in ("han_mask", "han_page", "han_readings"))
legacy = data("sjis_readings")
exceptions = []
index = 0
for lead, row in zip(LEADS, rows):
    if lead < 0x88:
        continue
    for trail, cp in zip(TRAILS, row):
        if lead == 0xfc and trail > 0x4b:
            break
        reading = 0
        if 0x4e00 <= cp < 0xa000:
            n = cp - 0x4e00
            word = n // 32
            bit = 1 << (n % 32)
            if mask[word] & bit:
                count = pages[n // 256] + (mask[word] & (bit - 1)).bit_count()
                count += sum(v.bit_count() for v in mask[(n // 256)*8:word])
                reading = packed(han, count)
        original = packed(legacy, index)
        if reading != original:
            exceptions.extend(((lead << 8) | trail, original))
        index += 1

(SRC / "remote_sjis_data.inc").write_text(
    "/* Generated by tools/remote-sjis/generate.py. */\n"
    + array("sjis_prefix", 8, prefix, '__attribute__((section(".sjis_prefix"))) ')
    + array("sjis_suffix", 8, suffix)
    + array("sjis_rows", 16, offsets)
    + array("sjis_pages", 8, ranges)
)
(SRC / "sjis_reading_exceptions.inc").write_text(
    "/* Generated by tools/remote-sjis/generate.py. */\n"
    + array("sjis_reading_exceptions", 16, exceptions)
)
print(f"Lookup data {len(prefix)} + {len(suffix)} bytes. OLED exceptions: {len(exceptions)//2}.")
