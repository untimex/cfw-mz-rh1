"""Generate the static Mandarin reading tables. Requires ICU uconv on PATH."""
import os
import re
import subprocess
import unicodedata
from pathlib import Path

START, END = 0x4e00, 0xa000
chars = [chr(i) for i in range(START, END)]
names = subprocess.check_output([os.environ.get("UCONV", "uconv"), "-x", "Han-Latin"],
                                input=("\n".join(chars) + "\n").encode()).decode().splitlines()
assert len(names) == len(chars)

def plain(name):
    decomposed = unicodedata.normalize("NFD", name.lower()).replace("u\u0308", "v")
    value = "".join(c for c in decomposed if not unicodedata.combining(c))
    return value if re.fullmatch("[a-z]+", value) else ""

reading = {c: plain(n) for c, n in zip(chars, names)}
syllables = [""] + sorted(set(reading.values()) - {""})
ids = {s: i for i, s in enumerate(syllables)}
assert len(ids) <= 512

def priority(c):
    if c.encode("gb2312", "ignore") or c.encode("cp932", "ignore"):
        return 0
    big5 = c.encode("cp950", "ignore")
    return int.from_bytes(big5, "big") if big5 else 0x10000

covered = set(sorted((c for c in chars if reading[c]), key=priority)[:13800])
mask, pages, dense = [], [], []
for start in range(0, len(chars), 32):
    if start % 256 == 0:
        pages.append(len(dense))
    bits = 0
    for n, c in enumerate(chars[start:start+32]):
        if c in covered:
            bits |= 1 << n
            dense.append(ids[reading[c]])
    mask.append(bits)

# A legal trail byte has 188 positions per row, skipping 0x7f.
sj = []
for lead in [*range(0x88, 0xa0), *range(0xe0, 0xeb), 0xed, 0xee, 0xfa, 0xfb, 0xfc]:
    for trail in [*range(0x40, 0x7f), *range(0x80, 0xfd)]:
        if lead == 0xfc and trail > 0x4b: break  # Last valid CP932 kanji is FC4B.
        c = bytes([lead,trail]).decode("cp932", errors="ignore")
        sj.append(ids.get(reading.get(unicodedata.normalize("NFKC",c), ""), 0))

def pack(values):
    bits = count = 0
    result = []
    for value in values:
        bits |= value << count
        count += 9
        while count >= 8:
            result.append(bits & 255)
            bits >>= 8
            count -= 8
    result.append(bits)
    return result

def array(name, width, values):
    lines = [", ".join(hex(x) for x in values[i:i+16]) for i in range(0,len(values),16)]
    return f"static const uint{width}_t {name}[] = {{\n    " + ",\n    ".join(lines) + "\n};\n"

text = "/* Generated by tools/pinyin/generate.py using ICU Han-Latin. */\n"
text += array("han_mask", 32, mask) + array("han_page", 16, pages)
text += array("han_readings", 8, pack(dense)) + array("sjis_readings", 8, pack(sj))
# Each spelling is at most six characters; use a single string and offsets.
offsets = []
pos = 0
for s in syllables:
    offsets.append(pos)
    pos += len(s)+1
text += array("spelling_offset",16,offsets)
text += 'static const char spellings[] =\n' + '\n'.join('    "'+s+'\\0"' for s in syllables)+';\n'
Path("src/extension-code/src/han_readings.inc").write_text(text)
print(len(covered), "Unicode readings;", len(syllables)-1, "spellings")
